const require = createRequire(import.meta.url);
const sourceDir = join(
  dirname(require.resolve('@material-symbols/svg-400/package.json')),
  'outlined',
);
const outFile = join(dirname(fileURLToPath(import.meta.url)), '../src/components/ui/icon-paths.ts');

const entries = ICONS.map((name) => {
  const svg = readFileSync(join(sourceDir, `${name}.svg`), 'utf8');
  const paths = [...svg.matchAll(/<path d="([^"]+)"/g)].map((match) => match[1]);
  if (paths.length === 0) throw new Error(`No path data found for icon "${name}"`);
  return `  ${name}: ${JSON.stringify(paths.join(' '))},`;
});

writeFileSync(
  outFile,
  `// Generated by scripts/generate-icons.mjs from Material Symbols (Apache-2.0). Do not edit.
export const iconPaths = {
${entries.join('\n')}
} as const;

export type IconName = keyof typeof iconPaths;
`,
);
process.stdout.write(`Wrote ${ICONS.length} icons to ${outFile}\n`);
